// Builds marketplace/guidelines/index.html from marketplace-api/lib/guidelines.json (the same file the review bot reads).
// Run: node tools/build-guidelines.mjs
import { readFileSync, writeFileSync } from "node:fs";
const g = JSON.parse(readFileSync(new URL("../marketplace-api/lib/guidelines.json", import.meta.url)));
// The server imports a plain module (no JSON import, which Vercel's builder may not trace).
writeFileSync(new URL("../marketplace-api/lib/guidelines.js", import.meta.url), "// Generated by tools/build-guidelines.mjs from guidelines.json. Do not edit.\nexport default " + JSON.stringify(g, null, 1) + ";\n");
const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);
const anchor = (id) => "g" + id.replace(".", "-");
const toc = g.sections.map((s) => `<li><a href="#s${s.n}">${s.n}. ${esc(s.title)}</a></li>`).join("");
const body = g.sections.map((s) => `<section class="gl" id="s${s.n}"><h2>${s.n}. ${esc(s.title)}</h2>${s.intro ? `<p>${esc(s.intro)}</p>` : ""}${s.items.map((i) => `<div class="gl__item" id="${anchor(i.id)}"><h3><a href="#${anchor(i.id)}">${i.id}</a> ${esc(i.title)}</h3><p>${esc(i.text)}</p></div>`).join("")}</section>`).join("\n");
writeFileSync(new URL("../marketplace/guidelines/index.html", import.meta.url), `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Merchant Content Review Guidelines | Maestro Pro Marketplace</title>
<meta name="description" content="The rules for selling sheet music, backing tracks and karaoke on the Maestro Pro Marketplace, and how every item is reviewed.">
<link rel="canonical" href="https://maestro-pro.app/marketplace/guidelines/">
<link rel="icon" href="/assets/favicon.png" type="image/png">
<link rel="stylesheet" href="/assets/maestro.css">
<link rel="stylesheet" href="/assets/marketplace.css">
</head>
<body class="read">
<a class="skip" href="#main">Skip to content</a>
<header class="top">
  <a class="top__brand" href="/"><img width="160" height="160" src="/assets/app-icon-160.png" alt="">Maestro Pro</a>
  <nav class="top__links" aria-label="Primary"><a href="/marketplace/">Marketplace</a><a href="/marketplace/account/">Account</a><a class="top__sell" href="/marketplace/onboard/">Sell</a></nav>
</header>
<main id="main" class="plain">
<h1>Marketplace Merchant Content Review Guidelines</h1>
<p class="mp-note">Last updated ${esc(g.updated)}</p>
${g.intro.map((p) => `<p>${esc(p)}</p>`).join("\n")}
<nav aria-label="Sections"><ol class="gl__toc">${toc}</ol></nav>
${body}
<p>Questions, appeals and copyright complaints: <a href="mailto:support@maestro-pro.app">support@maestro-pro.app</a>.</p>
</main>
<footer class="foot">
  <nav aria-label="Footer"><a href="/">Maestro Pro</a><a href="/marketplace/">Marketplace</a><a href="/support/">Support</a><a href="/privacy/">Privacy</a></nav>
  <p>&copy; <span id="yr">2026</span> The Caffeine Media Company.</p>
</footer>
<script>document.getElementById('yr').textContent=new Date().getFullYear()</script>
<script src="/assets/nav.js" defer></script>
</body>
</html>
`);
console.log("ok");
